//! Generate browser catalogs from the same metadata exported by WASM.
use std::{env, fmt::Write, fs, path::PathBuf};

use motion_core::layout::{self, FIELDS, Flag, SLOT_FIELDS};

fn main() {
    let mut ts = String::from("// Generated by cargo run -p motion-core --example contracts. Do not edit.\n");
    for (name, fields) in [("FIELDS", FIELDS), ("SLOT_FIELDS", SLOT_FIELDS)] {
        writeln!(ts, "export const {name} = [").unwrap();
        for (key, _, _) in fields {
            writeln!(ts, "  '{key}',").unwrap();
        }
        ts += "] as const;\n";
        writeln!(ts, "export const {name}_LENGTHS = {{").unwrap();
        for (key, _, len) in fields {
            writeln!(ts, "  {key}: {len},").unwrap();
        }
        ts += "} as const;\n";
    }
    ts += "export const FLAGS = [\n";
    for flag in Flag::ALL {
        writeln!(ts, "  '{flag:?}',").unwrap();
    }
    ts += "] as const;\nexport const DEFAULT_FLAGS = [\n";
    for flag in Flag::ALL.into_iter().filter(|f| f.default_value().is_some()) {
        writeln!(ts, "  '{flag:?}',").unwrap();
    }
    ts += "] as const;\n";
    // Reuse JSON metadata rather than maintaining another list of limits.
    let json = layout::json();
    let limits = json.split("\"limits\":").nth(1).unwrap().trim_end_matches('}');
    writeln!(ts, "export const LIMITS = {limits}}} as const;").unwrap();
    writeln!(ts, "export const ABI_VERSION = {};", layout::ABI_VERSION).unwrap();
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../web/src/generated/contracts.ts");
    if env::args().any(|arg| arg == "--check") {
        assert_eq!(fs::read_to_string(path).unwrap(), ts, "stale browser contracts: run make gen");
    } else {
        fs::write(path, ts).unwrap();
    }
}
