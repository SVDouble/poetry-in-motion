"""Emit the LaTeX of every symbolic quantity as a typed TypeScript module."""

from __future__ import annotations

from collections.abc import Callable

import sympy as sp

from .model import Derived, System, homogeneous, simp

HEADER = "// @generated by sym (motion_sym) — do not edit by hand.\n"

TYPES = (
    HEADER
    + """
/** Row-major matrix of LaTeX strings. */
export type TexMatrix = string[][];

export interface SymbolicFrame {
  /** Subscript name, e.g. `1` in g_{s1}. */
  name: string;
  parent: string;
  /** g_{parent,name}: homogeneous transform in SE(2). */
  local: TexMatrix;
  /** g_{s,name}: transform from the spatial frame. */
  world: TexMatrix;
}

export interface SymbolicTool {
  frame: string;
  /** Position p_st(q). */
  p: TexMatrix;
  /** ∂p_st/∂q. */
  Jp: TexMatrix;
  /** Spatial manipulator Jacobian (v_x, v_y, ω) × n. */
  Js: TexMatrix;
  /** Joint twists ξ_i in the reference configuration, columns (v_x, v_y, ω). */
  twists: TexMatrix;
  /** g_st(0). */
  gst0: TexMatrix;
}

export interface SymbolicModel {
  id: string;
  title: string;
  nq: number;
  /** LaTeX of each generalised coordinate. */
  q: string[];
  params: { id: string; tex: string }[];
  /** [shorthand, meaning] pairs, e.g. ["c_{1}", "\\\\cos\\\\theta_1"]. */
  trig: [string, string][];
  T: string;
  V: string;
  M: TexMatrix;
  C: TexMatrix;
  /** ∂V/∂q. */
  dV: TexMatrix;
  N: TexMatrix;
  B: TexMatrix;
  frames: SymbolicFrame[];
  tool: SymbolicTool | null;
}
"""
)


def _tex_fn(sys: System) -> Callable[[sp.Expr], str]:
    names: dict[sp.Symbol, str] = {}
    for s, t in zip(sys.q, sys.q_tex, strict=True):
        names[s] = t
    for s, t in zip(sys.qd, sys.q_tex, strict=True):
        base, sep, sub = t.partition("_")  # \theta_{1} -> \dot{\theta}_{1}
        names[s] = r"\dot{" + base + "}" + sep + sub
    for p in sys.params:
        names[p.symbol] = p.tex
    for sym, t in sys.trig.values():
        names[sym] = t
    subs = {k: v[0] for k, v in sys.trig.items()}

    def tex(e: sp.Expr) -> str:
        e = sp.sympify(e)
        if subs:
            e = e.subs(subs)
        return str(sp.latex(e, symbol_names=names))

    return tex


def _s(s: str) -> str:
    return "String.raw`" + s.replace("`", "\\`") + "`"


def _mat(tex: Callable[[sp.Expr], str], m: sp.Matrix) -> str:
    rows = ["[" + ", ".join(_s(tex(m[i, j])) for j in range(m.shape[1])) + "]" for i in range(m.shape[0])]
    return "[" + ", ".join(rows) + "]"


def emit(sys: System, d: Derived) -> str:
    tex = _tex_fn(sys)
    names = _tex_fn(System(**{**sys.__dict__, "trig": {}}))  # trig legend shows the full functions

    frames = [
        f"    {{ name: {_s(f.name)}, parent: {_s(f.parent)}, "
        f"local: {_mat(tex, homogeneous(f.local))}, "
        f"world: {_mat(tex, homogeneous(d.world[f.name]).applyfunc(simp))} }},"
        for f in sys.frames
    ]
    params = "\n".join(f"    {{ id: '{p.ident}', tex: {_s(p.tex)} }}," for p in sys.params)
    trig = "\n".join(f"    [{_s(t)}, {_s(names(k))}]," for k, (_, t) in sys.trig.items())

    tool = "null"
    if sys.tool and d.tool_p is not None and d.Jp is not None and d.Js is not None and d.twists is not None:
        gst0 = homogeneous(tuple(e.subs({qi: 0 for qi in sys.q}) for e in d.world[sys.tool]))
        tool = (
            "{\n"
            f"    frame: {_s(sys.tool)},\n"
            f"    p: {_mat(tex, d.tool_p)},\n"
            f"    Jp: {_mat(tex, d.Jp)},\n"
            f"    Js: {_mat(tex, d.Js)},\n"
            f"    twists: {_mat(tex, d.twists)},\n"
            f"    gst0: {_mat(tex, gst0.applyfunc(simp))},\n"
            "  }"
        )

    lines = [
        HEADER,
        "import type { SymbolicModel } from './types';",
        "",
        f"export const {sys.ident}: SymbolicModel = {{",
        f"  id: '{sys.ident}',",
        f"  title: {_s(sys.title)},",
        f"  nq: {len(sys.q)},",
        "  q: [" + ", ".join(_s(t) for t in sys.q_tex) + "],",
        "  params: [\n" + params + "\n  ],",
        "  trig: [" + ("\n" + trig + "\n  " if trig else "") + "],",
        f"  T: {_s(tex(d.T))},",
        f"  V: {_s(tex(d.V))},",
        f"  M: {_mat(tex, d.M)},",
        f"  C: {_mat(tex, d.C)},",
        f"  dV: {_mat(tex, d.dV)},",
        f"  N: {_mat(tex, d.N)},",
        f"  B: {_mat(tex, sys.actuation)},",
        "  frames: [\n" + "\n".join(frames) + "\n  ],",
        f"  tool: {tool},",
        "};",
        "",
    ]
    return "\n".join(lines)
