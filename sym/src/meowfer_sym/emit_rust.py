"""Emit allocation-free Rust kernels (common-subexpression eliminated) from a derived model."""

from __future__ import annotations

from typing import ClassVar

import sympy as sp
from sympy.printing.c import C99CodePrinter

from .model import Derived, System

HEADER = "// @generated by sym (meowfer_sym) — do not edit by hand.\n"


class F64Printer(C99CodePrinter):
    """Rust printer built on the C99 printer (whose parenthesisation is reliable).

    SymPy's own RustCodePrinter drops parentheses in products such as ``c*(a + b)*th.sin()``, so we print
    associated-function calls (``f64::sin(x)``) instead of method calls and keep every literal an f64.
    """

    _FUNCS: ClassVar[dict[str, str]] = {"sin": "sin", "cos": "cos", "tan": "tan", "exp": "exp", "log": "ln"}

    def _print_Integer(self, e: sp.Integer) -> str:
        return f"{int(e)}.0"

    def _print_Rational(self, e: sp.Rational) -> str:
        return f"({int(e.p)}.0 / {int(e.q)}.0)"

    def _print_Function(self, e: sp.Function) -> str:
        name = self._FUNCS.get(type(e).__name__)
        if name is None:
            raise NotImplementedError(f"no Rust mapping for {type(e).__name__}")
        return f"f64::{name}({', '.join(self._print(a) for a in e.args)})"

    _print_sin = _print_cos = _print_tan = _print_exp = _print_log = _print_Function

    def _print_Pow(self, e: sp.Pow) -> str:
        base, ex = e.as_base_exp()
        b = self._print(base)
        if ex.is_Integer:
            k = int(ex)
            if k == -1:
                return f"f64::recip({b})"
            if k < 0:
                return f"f64::recip(f64::powi({b}, {-k}))"
            return f"f64::powi({b}, {k})"
        if ex == sp.Rational(1, 2):
            return f"f64::sqrt({b})"
        return f"f64::powf({b}, {self._print(ex)})"


_printer = F64Printer()


def rs(e: sp.Expr) -> str:
    return str(_printer.doprint(e))


def _fn(
    name: str,
    args: str,
    sys: System,
    outputs: list[tuple[str, sp.Expr]],
    ret: str | None = None,
) -> str:
    exprs = [sp.sympify(e) for _, e in outputs]
    repl, reduced = sp.cse(exprs, symbols=sp.numbered_symbols("t"), optimizations="basic")
    used = set().union(*(e.free_symbols for e in exprs)) if exprs else set()
    used_names = {s.name for s in used}

    body: list[str] = []
    for i, s in enumerate(sys.q):
        if s.name in used_names:
            body.append(f"    let {s.name} = q[{i}];")
    for i, s in enumerate(sys.qd):
        if s.name in used_names:
            body.append(f"    let {s.name} = qd[{i}];")
    for i, p in enumerate(sys.params):
        if p.symbol.name in used_names:
            body.append(f"    let {p.symbol.name} = p[{i}];")
    body += [f"    let {sym} = {rs(e)};" for sym, e in repl]
    if ret:
        body.append("    [" + ", ".join(rs(e) for e in reduced) + "]")
    else:
        body += [f"    {target} = {rs(e)};" for (target, _), e in zip(outputs, reduced, strict=True)]

    sig = f"pub fn {name}({args})" + (f" -> {ret}" if ret else "")
    return f"#[inline]\n{sig} {{\n" + "\n".join(body) + "\n}\n"


def _mat(name: str, m: sp.Matrix) -> list[tuple[str, sp.Expr]]:
    r, c = m.shape
    return [(f"{name}[{i * c + j}]", m[i, j]) for i in range(r) for j in range(c)]


def emit(sys: System, d: Derived) -> str:
    n = len(sys.q)
    frame_names = ["s", *(f.name for f in sys.frames)]
    nu = sys.actuation.shape[1]
    pq = "p: &[f64], q: &[f64]"
    pqqd = "p: &[f64], q: &[f64], qd: &[f64]"

    out = [
        HEADER,
        f"//! {sys.title}: kernels for M(q) q̈ + C(q, q̇) q̇ + N(q, q̇) = τ.",
        "#![allow(unused_variables, non_snake_case, clippy::all, clippy::pedantic, clippy::nursery)]",
        "",
        f"pub const NQ: usize = {n};",
        f"pub const NP: usize = {len(sys.params)};",
        f"pub const NU: usize = {nu};",
        f"pub const NFRAMES: usize = {len(frame_names)};",
        f"pub const NBODIES: usize = {len(sys.bodies)};",
        f"pub const HAS_TOOL: bool = {'true' if sys.tool else 'false'};",
        "pub const PARAMS: [&str; NP] = [" + ", ".join(f'"{p.ident}"' for p in sys.params) + "];",
        "/// Indices of the damping coefficients β_i inside the parameter vector.",
        "pub const DAMPING: [usize; NQ] = ["
        + ", ".join(str(next(i for i, p in enumerate(sys.params) if p.symbol == b)) for b in sys.damping)
        + "];",
        "/// Actuation matrix B (row-major NQ × NU), τ = B u.",
        "pub const B: [f64; NQ * NU] = [" + ", ".join(repr(float(v)) for v in sys.actuation) + "];",
        "",
        "/// Inertia matrix M(q), Coriolis matrix C(q, q̇) and N(q, q̇) = ∂V/∂q + β ⊙ q̇.",
        _fn(
            "mcn",
            pqqd + ", m: &mut [f64], c: &mut [f64], n: &mut [f64]",
            sys,
            _mat("m", d.M) + _mat("c", d.C) + _mat("n", d.N),
        ),
        "/// Ṁ(q, q̇).",
        _fn("mdot", pqqd + ", out: &mut [f64]", sys, _mat("out", d.Mdot)),
        "/// ∂N/∂q at q̇ = 0 (gravity stiffness, used for linearisation).",
        _fn("dndq", pq + ", out: &mut [f64]", sys, _mat("out", d.dNdq)),
        "/// Gravity / potential part of N: ∂V/∂q.",
        _fn("dvdq", pq + ", out: &mut [f64]", sys, [(f"out[{i}]", d.dV[i]) for i in range(n)]),
        "/// Kinetic and potential energy [T, V].",
        _fn("energy", pqqd, sys, [("", d.T), ("", d.V)], ret="[f64; 2]"),
    ]

    poses: list[tuple[str, sp.Expr]] = []
    for k, nm in enumerate(frame_names):
        x, y, phi = d.world[nm]
        poses += [(f"out[{3 * k}]", x), (f"out[{3 * k + 1}]", y), (f"out[{3 * k + 2}]", phi)]
    out.append("/// Spatial poses (x, y, φ) of g_s{" + ", ".join(frame_names) + "}.")
    out.append(_fn("frames", pq + ", out: &mut [f64]", sys, poses))

    coms: list[tuple[str, sp.Expr]] = []
    for k, b in enumerate(sys.bodies):
        coms += [(f"out[{2 * k}]", b.com[0]), (f"out[{2 * k + 1}]", b.com[1])]
    out.append("/// Centre-of-mass positions of each body in the spatial frame.")
    out.append(_fn("coms", pq + ", out: &mut [f64]", sys, coms))

    if d.Jp is not None and d.Js is not None and d.tool_p is not None:
        out.append(
            "/// Tool position p_st, its Jacobian ∂p/∂q (2 × NQ) and the spatial Jacobian J^s (3 × NQ)."
        )
        out.append(
            _fn(
                "tool",
                pq + ", pos: &mut [f64], jp: &mut [f64], js: &mut [f64]",
                sys,
                [("pos[0]", d.tool_p[0]), ("pos[1]", d.tool_p[1]), *_mat("jp", d.Jp), *_mat("js", d.Js)],
            )
        )
    else:
        out.append(
            "pub fn tool(_p: &[f64], _q: &[f64], _pos: &mut [f64], _jp: &mut [f64], _js: &mut [f64]) {}\n"
        )
    return "\n".join(out)
